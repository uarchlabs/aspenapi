#pragma once
#include <stdint.h>
#include <vector>
#include <string>

namespace aspen
{
// ------------------------------------------------------------------
// ------------------------------------------------------------------
struct Nvp
{
  Nvp()
    : name(""),
      value("")
  {}

  Nvp(std::string _n,std::string _v)
    : name(_n),
      value(_v)
  {}
  
 ~Nvp() {}

  std::string name;
  std::string value;
};
// ==================================================================
struct Nvt : public Nvp
{
  // ----------------------------------------------------------------
  Nvt()
    : Nvp("",""),
      type("")
  {}
  // ----------------------------------------------------------------
  Nvt(std::string _n,std::string _v,std::string _t)
    : Nvp(_n,_v),
      type(_t)
  {}
  // ----------------------------------------------------------------
 ~Nvt() {}
  // ----------------------------------------------------------------
  // ----------------------------------------------------------------
  std::string type;
};

}
