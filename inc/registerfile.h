#pragma once
#include "register.h"
#include <vector>
#include <string>

namespace aspen
{
// ------------------------------------------------------------------
// ------------------------------------------------------------------
struct RegisterFile
{
  // ----------------------------------------------------------------
  // ----------------------------------------------------------------
  RegisterFile(std::string _n="",uint32_t _w=0,std::string _t="")
    : name(_n),
      width(_w),
      type(_t),
      regs()
  {}
  // ----------------------------------------------------------------
  // ----------------------------------------------------------------
  RegisterFile(std::string _n,uint32_t _w,std::string _t,
               std::vector<Register> &_r)
    : name(_n),
      width(_w),
      type(_t),
      regs(_r)
  {}
  // ----------------------------------------------------------------
  // ----------------------------------------------------------------
 ~RegisterFile() {}

  // ----------------------------------------------------------------
  // ----------------------------------------------------------------
  std::string name;
  uint32_t width;
  std::string type;
  std::vector<Register> regs;

};

}
